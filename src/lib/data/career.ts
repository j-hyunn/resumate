function parseInput<S extends z.ZodType>(schema: S, input: unknown): z.output<S> {
  const parsed = schema.safeParse(input)
  if (!parsed.success) unwrap(invalid(parsed.error))
  return parsed.data as z.output<S>
}

/** QA-W5-07: Server Action arguments are any JSON; a non-object patch is `invalid_input`, not a TypeError. */
function requirePatch(patch: unknown): void {
  if (!patch || typeof patch !== "object" || Array.isArray(patch)) throw new AppError("invalid_input")
}

function defined(values: Record<string, unknown>): Record<string, unknown> {
  return Object.fromEntries(Object.entries(values).filter(([, v]) => v !== undefined))
}

/** DB date ('YYYY-MM-01') → the contract's 'YYYY-MM'. */
function toYearMonth(value: string | null | undefined): string | null | undefined {
  return typeof value === "string" ? value.slice(0, 7) : value
}

/**
 * id / expectedUpdatedAt of the auto-save contract (S2 `upsertRow`). A given id must exist: never re-creates a deleted row.
 * QA-W5-06 (2): neither does a `client_id` retry of a row this browser deleted meanwhile (→ not_found = `gone`).
 */
async function saveIdentity(id: string | null, opts: WriteOptions | undefined, current: (id: string) => Promise<{ updated_at: string } | null>) {
  if (!id) {
    if (!opts?.client_id) return { id: randomUUID() }
    const { user } = await requireConsentedUser()
    if (await wasRowDeleted(user.id, opts.client_id)) throw new AppError("not_found")
    return { id: opts.client_id }
  }
  if (opts?.expected_updated_at) return { id, expectedUpdatedAt: opts.expected_updated_at }
  const row = await current(id)
  if (!row) throw new AppError("not_found")
  return { id, expectedUpdatedAt: row.updated_at }
}

function saved<T>(row: T | null): T {
  if (!row) throw new AppError("not_found")
  return row
}

