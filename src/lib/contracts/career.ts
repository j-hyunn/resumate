// ---------- year-month ----------

/** 1900–2099 only, so an out-of-range year is a 400 here instead of a DB 22008 (QA-S2-01). */
const YEAR_MONTH_RE = /^((?:19|20)\d{2})-(0[1-9]|1[0-2])$/;

/** `'YYYY-MM'` → `'YYYY-MM-01'` (DB date). */
export function yearMonthToDate(ym: string): string {
  if (!YEAR_MONTH_RE.test(ym)) throw new Error("invalid year-month");
  return `${ym}-01`;
}

/** DB date (`'YYYY-MM-DD'`) → `'YYYY-MM'`. */
export function dateToYearMonth(date: string | null): string | null {
  return date === null ? null : date.slice(0, 7);
}

const yearMonth = z.string().regex(YEAR_MONTH_RE, "YYYY-MM");

// ---------- field helpers ----------

/** Optional, nullable trimmed text; `''` → null. */
const text = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .nullable()
    .transform((v) => (v === "" ? null : v))
    .optional();

const nullableYearMonth = z
  .union([yearMonth, z.literal("")])
  .nullable()
  .transform((v) => (v === "" ? null : v))
  .optional();

/**
 * Id format check only (`z.guid()`): Postgres uuid accepts any 8-4-4-4-12 hex,
 * not just RFC 4122 versions, so `z.uuid()` would reject valid stored ids (QA-S2-02).
 */
const uuid = z.guid();

/**
 * Auto-save identity (QA-S2-03, decisions 2026-10-25):
 * - `id` is generated by the client (`crypto.randomUUID()`) for a new row and reused
 *   on every save of that row, so a retried create never makes a duplicate.
 * - `expectedUpdatedAt`: the `updatedAt` the client last saw (optimistic concurrency,
 *   mismatch → `conflict`). Omit it until the first save has succeeded.
 */
const saveMeta = {
  id: uuid,
  expectedUpdatedAt: z.iso.datetime({ offset: true }).optional(),
};

function endNotBeforeStart(v: { startMonth?: string | null; endMonth?: string | null }): boolean {
  return !v.startMonth || !v.endMonth || v.endMonth >= v.startMonth;
}

// ---------- experiences (DM A.3, S-09) ----------

export const SaveExperienceInput = z
  .object({
    ...saveMeta,
    companyName: text(CAREER_LIMITS.experience.companyName),
    startMonth: nullableYearMonth,
    endMonth: nullableYearMonth,
    isCurrent: z.boolean().optional(),
    jobRank: text(CAREER_LIMITS.experience.jobRank),
    jobPosition: text(CAREER_LIMITS.experience.jobPosition),
    department: text(CAREER_LIMITS.experience.department),
    employmentType: z.enum(EMPLOYMENT_TYPES).nullable().optional(),
    summary: text(CAREER_LIMITS.experience.summary),
  })
  .refine(endNotBeforeStart, { message: "end_before_start", path: ["endMonth"] })
  .refine((v) => !(v.isCurrent === true && v.endMonth), { message: "current_with_end", path: ["endMonth"] });
export type SaveExperienceInput = z.input<typeof SaveExperienceInput>;
export type SaveExperiencePatch = z.output<typeof SaveExperienceInput>;

