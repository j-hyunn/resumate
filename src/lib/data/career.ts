export interface CareerTreeAffiliationEntry {
  kind: "experience" | "education"
  experience?: Experience
  education?: Education
  /** projects that started in this year */
  projects: ProjectWithChildren[]
  /** true when no project started in this year → collapsed header only */
  collapsed: boolean
}

export interface CareerTreeYear {
  year: number
  entries: CareerTreeAffiliationEntry[]
  /** 기타 프로젝트 (no affiliation) started this year */
  other_projects: ProjectWithChildren[]
}

export interface CareerTree {
  years: CareerTreeYear[]
  /** 연도 미정 (no affiliation and no period) */
  undated_projects: ProjectWithChildren[]
  /** W2-④: an experience / education without a start month, under 연도 미정 instead of nowhere */
  undated_entries: CareerTreeAffiliationEntry[]
  counts: {
    complete_experiences: number
    complete_educations: number
    complete_projects: number
    complete_project_details: number
  }
  /** 규칙 기반 안내 1줄 inputs (S-08 상단 요약) */
  hints: {
    details_without_result: number
    projects_without_detail: number
  }
  skill_count: number
  profile: Profile
  active_writing_chats: WritingChat[]
  is_empty: boolean
}

function yearOf(date: string | null): number | null {
  return date ? Number(date.slice(0, 4)) : null
}

export async function getCareerTree(): Promise<CareerTree> {
  return previewOr(mockCareerTree, realCareerTree)
}

function careerTreeTotals(db: CareerData, profile: Profile): Omit<CareerTree, "years" | "undated_projects" | "undated_entries"> {
  return {
    counts: {
      complete_experiences: db.experiences.filter((e) => e.status === "complete").length,
      complete_educations: db.educations.filter((e) => e.status === "complete").length,
      complete_projects: db.projects.filter((p) => p.status === "complete").length,
      complete_project_details: db.project_details.filter((d) => d.status === "complete").length,
    },
    hints: {
      details_without_result: db.project_details.filter((d) => !d.result).length,
      projects_without_detail: db.projects.filter((p) => !db.project_details.some((d) => d.project_id === p.id)).length,
    },
    skill_count: db.skills.length,
    profile,
    active_writing_chats: db.writing_chats
      .filter((c) => c.status === "active")
      .sort((a, b) => b.last_activity_at.localeCompare(a.last_activity_at)),
    is_empty: db.experiences.length + db.educations.length + db.projects.length === 0,
  }
}

/**
 * S-08 on the real year view (DM §2.4, `groupCareerByYear`): a project dated outside its affiliation's
 * years still shows under that affiliation. The `year: null` bucket maps to `undated_entries` (an experience /
 * education without a start month, with its undated projects) and `undated_projects` (no affiliation).
 */
async function realCareerTree(): Promise<CareerTree> {
  const { supabase, user } = await requireConsentedUser()
  const [rows, profile] = await Promise.all([loadCareerRows(supabase), loadProfileRow(supabase, user.id)])
  const db = rows as unknown as CareerData
  const projects = new Map(db.projects.map((p) => [p.id, projectWithChildren(db, p)]))
  const pick = (ids: string[]) => ids.flatMap((id) => projects.get(id) ?? [])
  const groups = career.groupCareerByYear(
    {
      experiences: db.experiences.map((e) => ({ id: e.id, startMonth: e.start_month, endMonth: e.end_month, isCurrent: e.is_current })),
      educations: db.educations.map((e) => ({ id: e.id, startMonth: e.start_month, endMonth: e.end_month })),
      projects: db.projects.map((p) => ({ id: p.id, experienceId: p.experience_id, educationId: p.education_id, startMonth: p.start_month, createdAt: p.created_at })),
    },
    career.currentYearInSeoul(new Date()),
  )
  const years: CareerTreeYear[] = []
  const undated: ProjectWithChildren[] = []
  const undatedEntries: CareerTreeAffiliationEntry[] = []
  const entriesOf = (affiliations: (typeof groups)[number]["affiliations"]) =>
    affiliations.flatMap((a): CareerTreeAffiliationEntry[] => {
      const inYear = pick(a.projectIds)
      const experience = a.type === "experience" ? db.experiences.find((e) => e.id === a.id) : undefined
      const education = a.type === "education" ? db.educations.find((e) => e.id === a.id) : undefined
      if (!experience && !education) return []
      return [{ kind: a.type, ...(experience ? { experience } : { education }), projects: inYear, collapsed: inYear.length === 0 }]
    })
  for (const group of groups) {
    if (group.year === null) {
      undatedEntries.push(...entriesOf(group.affiliations))
      undated.push(...pick(group.otherProjectIds))
      continue
    }
    years.push({ year: group.year, entries: entriesOf(group.affiliations), other_projects: pick(group.otherProjectIds) })
  }
  return { years, undated_projects: undated, undated_entries: undatedEntries, ...careerTreeTotals(db, profile as Profile) }
}

async function mockCareerTree(): Promise<CareerTree> {
  const db = await mockRequest()
  const thisYear = new Date().getFullYear()
  const projects = db.projects.map((p) => projectWithChildren(db, p))
  const yearMap = new Map<number, CareerTreeYear>()
  const ensureYear = (year: number) => {
    let y = yearMap.get(year)
    if (!y) {
      y = { year, entries: [], other_projects: [] }
      yearMap.set(year, y)
    }
    return y
  }

  const projectYear = (p: ProjectWithChildren): number | null =>
    yearOf(p.start_month) ?? yearOf(p.experience?.start_month ?? null) ?? yearOf(p.education?.start_month ?? null)

  const undatedEntries: CareerTreeAffiliationEntry[] = []
  const addAffiliation = (
    kind: "experience" | "education",
    row: Experience | Education,
    ongoing: boolean,
    ownProjects: ProjectWithChildren[],
  ) => {
    const start = yearOf(row.start_month)
    if (start === null) {
      undatedEntries.push({
        kind,
        ...(kind === "experience" ? { experience: row as Experience } : { education: row as Education }),
        projects: ownProjects,
        collapsed: ownProjects.length === 0,
      })
      return
    }
    const end = yearOf(row.end_month) ?? (ongoing ? thisYear : start)
    for (let year = end; year >= start; year -= 1) {
      const inYear = ownProjects.filter((p) => projectYear(p) === year)
      ensureYear(year).entries.push({
        kind,
        ...(kind === "experience" ? { experience: row as Experience } : { education: row as Education }),
        projects: inYear,
        collapsed: inYear.length === 0,
      })
    }
  }

  for (const exp of db.experiences) {
    addAffiliation("experience", exp, exp.is_current, projects.filter((p) => p.experience_id === exp.id))
  }
  for (const edu of db.educations) {
    addAffiliation("education", edu, edu.enrollment_status === "enrolled", projects.filter((p) => p.education_id === edu.id))
  }
  const undated: ProjectWithChildren[] = []
  for (const p of projects) {
    // an affiliation without a start month lists its projects itself (undated_entries)
    if (p.experience_id || p.education_id) continue
    const year = projectYear(p)
    if (year === null) undated.push(p)
    else ensureYear(year).other_projects.push(p)
  }

  const years = [...yearMap.values()].sort((a, b) => b.year - a.year)
  for (const y of years) {
    y.entries.sort((a, b) => {
      const sa = (a.experience ?? a.education)?.start_month ?? ""
      const sb = (b.experience ?? b.education)?.start_month ?? ""
      return sb.localeCompare(sa)
    })
  }

  return clone({ years, undated_projects: undated, undated_entries: undatedEntries, ...careerTreeTotals(db, db.profiles[0]) })
}

