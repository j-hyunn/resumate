/** project_skills tags by skill name; creates skills by normalized_name (S-10 사용 기술) */
export async function setProjectSkills(projectId: string, names: string[], opts?: WriteOptions): Promise<Skill[]> {
  return previewOr(
    () => mockSetProjectSkills(projectId, names, opts),
    async () => {
      const { supabase, user } = await requireConsentedUser()
      if (!Array.isArray(names) || names.some((n) => typeof n !== "string")) requirePatch(null)
      const wanted = new Set(names.map((n) => normalizeSkillName(n)).filter(Boolean))
      const current = await loadProjectSkillRows(supabase, projectId)
      for (const skill of current) {
        if (wanted.has(normalizeSkillName(skill.name))) continue
        await career.removeProjectSkill(supabase, parseInput(RemoveProjectSkillInput, { projectId, skillId: skill.id }))
      }
      const result: Skill[] = []
      for (const name of names.map((n) => n.trim()).filter(Boolean)) {
        const { skill } = await career.addProjectSkill(supabase, parseInput(AddProjectSkillInput, { projectId, name }))
        result.push(skillRow(skill, user.id))
      }
      return result
    },
  )
}

async function mockSetProjectSkills(projectId: string, names: string[], opts?: WriteOptions): Promise<Skill[]> {
  const db = await mockRequest()
  maybeFail(opts)
  const normalized = (n: string) => n.trim().toLowerCase().replace(/\s+/g, "")
  db.project_skills = db.project_skills.filter((ps) => ps.project_id !== projectId)
  const result: Skill[] = []
  for (const name of names.map((n) => n.trim()).filter(Boolean)) {
    let skill = db.skills.find((s) => s.normalized_name === normalized(name))
    if (!skill) {
      skill = { ...baseRow(), name, normalized_name: normalized(name), is_manual: false, proficiency: null }
      db.skills.push(skill)
    }
    db.project_skills.push({ project_id: projectId, skill_id: skill.id, user_id: USER_ID, created_at: new Date().toISOString() })
    result.push(skill)
  }
  // 고아 태그 스킬 정리 (is_manual = false, 연결 0)
  db.skills = db.skills.filter((s) => s.is_manual || db.project_skills.some((ps) => ps.skill_id === s.id))
  touchCareer(db)
  return clone(result)
}

