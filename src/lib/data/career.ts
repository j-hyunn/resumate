type ExperiencePatch = Partial<Omit<Experience, "id" | "user_id" | "created_at" | "updated_at" | "status">>

export async function saveExperience(id: string | null, patch: ExperiencePatch, opts?: WriteOptions): Promise<Experience> {
  return previewOr(
    () => mockSaveExperience(id, patch, opts),
    async () => {
      const { supabase } = await requireConsentedUser()
      requirePatch(patch)
      const identity = await saveIdentity(id, opts, (rowId) => loadExperienceRow(supabase, rowId))
      const input = parseInput(SaveExperienceInput, {
        ...identity,
        ...defined({
          companyName: patch.company_name,
          startMonth: toYearMonth(patch.start_month),
          endMonth: patch.is_current ? null : toYearMonth(patch.end_month),
          isCurrent: patch.is_current,
          jobRank: patch.job_rank,
          jobPosition: patch.job_position,
          department: patch.department,
          employmentType: patch.employment_type,
          summary: patch.summary,
        }),
      })
      const result = await career.saveExperience(supabase, input)
      return saved(await loadExperienceRow(supabase, result.id)) as Experience
    },
  )
}

async function mockSaveExperience(id: string | null, patch: ExperiencePatch, opts?: WriteOptions): Promise<Experience> {
  const db = await mockRequest()
  maybeFail(opts)
  let row = id ? db.experiences.find((e) => e.id === id) : undefined
  if (!row) {
    row = {
      ...baseRow(),
      status: "draft",
      company_name: null,
      start_month: null,
      end_month: null,
      is_current: false,
      job_rank: null,
      job_position: null,
      department: null,
      employment_type: null,
      summary: null,
    }
    db.experiences.push(row)
  }
  Object.assign(row, patch)
  if (row.is_current) row.end_month = null
  row.status = isExperienceComplete(row) ? "complete" : "draft"
  stamp(row)
  touchCareer(db)
  return clone(row)
}

