// ---------- skills (DM A.4, S-12, F-P1-05) ----------

/** Trim + collapse inner whitespace; the DB lowercases for normalized_name. */
const skillName = z
  .string()
  .transform((v) => v.trim().replace(/\s+/g, " "))
  .pipe(z.string().min(1).max(CAREER_LIMITS.skill.name));

/**
 * Mirrors the generated `skills.normalized_name` ([가정] spec-gaps 2026-10-25):
 * btrim → collapse whitespace → lower. Used to find an existing skill before insert.
 */
export function normalizeSkillName(name: string): string {
  return name.trim().replace(/\s+/g, " ").toLowerCase();
}

